"""Write the research-cost BATCH overlays (Director ruling 2026-10-26, work item 5) from decision-table.csv.

Each batch is a research overlay ({"nodes": {id: {"magnitudeStep": s}}}) applied ON TOP of the calibrated trial overlay
and measured on its own against it (Sim.Tests ResearchEconomyMeasurement.OverlayRun_FourSeeds). Nothing is written to
research.json. Held, never batched: FUTURE-DEPENDENT and EFFECT-DEFECT rows (priced for a system that does not exist yet,
or re-pointed by CR-025), PLACEHOLDER-ONLY rows (five of seven are in the 17-node audit), and any node in CR-025 or the
17-node audit.

Usage: python3 -I tools/cost_batch_overlays.py <out-dir>
"""
import csv
import json
import sys
from pathlib import Path

PASS = Path(__file__).resolve().parent.parent / "research-cost-pass"
HELD_IDS = set(
    "kiln_updraft oil_press papyrus plank_boat fulling_mill sulphuric_acid telephone petroleum_refining integrated_circuit "
    "nuclear_power solar_pv wind_turbine_modern cloud_computing desalination fusion_power trace_italienne rocket "
    "horse_domestication horseshoe internal_combustion bridge_stone bridge_trusts turnpike_trusts sprung_coach road_houses "
    "wheel_spoked saddle aluminium integrated_alliance_command pilgrimage road_traffic_regulation".split())

# (batch, description, class, tree or None, Ages) — small batches, split by direction, tree and Age band
BATCHES = [
    ("b0-early-six", "the six early enablers, -0.5 each (x0.71)", "EARLY-ENABLER", None, range(1, 3)),
    ("b1-under-a3-5", "under-priced, Ages 3-5, both trees (increases)", "UNDER-PRICED", None, range(3, 6)),
    ("b2-under-a6-9-tech", "under-priced technologies, Ages 6-9 (increases)", "UNDER-PRICED", "technology", range(6, 10)),
    ("b3-under-a6-9-civ", "under-priced civics, Ages 6-9 (increases)", "UNDER-PRICED", "civics", range(6, 10)),
    ("b4-low-a1-4", "low-value, Ages 1-4, both trees (reductions)", "LOW-VALUE", None, range(1, 5)),
    ("b5-low-a5-7", "low-value, Ages 5-7, both trees (reductions)", "LOW-VALUE", None, range(5, 8)),
    ("b6-low-a8-9-tech", "low-value technologies, Ages 8-9 (reductions)", "LOW-VALUE", "technology", range(8, 10)),
    ("b7-low-a8-9-civ", "low-value civics, Ages 8-9 (reductions)", "LOW-VALUE", "civics", range(8, 10)),
]


def main(argv):
    out = Path(argv[0])
    out.mkdir(parents=True, exist_ok=True)
    rows = list(csv.DictReader(open(PASS / "decision-table.csv", encoding="utf-8")))
    seen = set()
    for name, desc, cls, tree, ages in BATCHES:
        pick = [r for r in rows if r["class"] == cls and (tree is None or r["tree"] == tree) and int(r["age"]) in ages
                and r["id"] not in HELD_IDS]
        pick.sort(key=lambda r: (r["tree"], int(r["age"]), r["id"]))
        assert not (seen & {r["id"] for r in pick}), name
        seen |= {r["id"] for r in pick}
        doc = {"_doc": f"Cost batch {name}: {desc}. Generated by tools/cost_batch_overlays.py from decision-table.csv; "
                       "measured on top of the trial overlay, never applied to research.json.",
               "nodes": {r["id"]: {"magnitudeStep": float(r["factorStep"])} for r in pick}}
        with open(out / f"{name}.json", "w", encoding="utf-8") as fh:
            json.dump(doc, fh, indent=1, ensure_ascii=True)
            fh.write("\n")
        print(f"{name:20s} {len(pick):3d} nodes  {desc}")
    held = [r for r in rows if r["id"] not in seen]
    print(f"held (not batched): {len(held)} rows")


if __name__ == "__main__":
    main(sys.argv[1:])
