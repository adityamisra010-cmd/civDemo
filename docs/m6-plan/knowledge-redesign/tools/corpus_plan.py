#!/usr/bin/env python3
"""Split the active proposed nodes into corpus topic files for the writing stage.

DESIGN-PACKAGE TOOLING ONLY. Reads the canonical proposal files; writes
corpus/plan.json (batches: file, title, lane, source-id prefix, node ids) and
corpus/index.json (the file list the validator and renderer read). Deterministic:
nodes are ordered by (lane, Age, key) and batches are cut at a fixed size.

Usage: python3 -I tools/corpus_plan.py [--batch 36]
"""
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kr_lib as kr  # noqa: E402

TITLES = {
    "D01-agriculture-food": ("agriculture-food", "Agriculture and food", "AGR"),
    "D02-materials-mining": ("materials-mining", "Materials, metallurgy and mining", "MAT"),
    "D03-science-early": ("science-early", "Early science and mathematics", "SCI"),
    "D04-natural-science": ("natural-science", "Natural science", "NAT"),
    "D05-communication-computing": ("communication-computing", "Communication and computing", "COM"),
    "D06-energy-engineering": ("energy-engineering", "Energy and engineering", "ENG"),
    "D07-industry-construction": ("industry-construction", "Industry, construction and infrastructure", "IND"),
    "D08-transport-naval": ("transport-naval", "Transport, navigation and naval", "TRN"),
    "D09-military": ("military", "Military technology", "MIL"),
    "D10-medicine": ("medicine", "Medicine and public health", "MED"),
    "D11-nuclear-geology": ("nuclear-geology", "Geology, resource knowledge and nuclear science", "NUC"),
    "D12-civics": ("civics", "Civics (micro and macro)", "CIV"),
}


def main(argv):
    size = int(argv[argv.index("--batch") + 1]) if "--batch" in argv else 36
    tech = kr.load_json(kr.PKG / "technology-tree-proposal.json")
    civ = kr.load_json(kr.PKG / "civics-tree-proposal.json")
    nodes = [n for n in tech["nodes"] + civ["nodes"] if n["status"] != "retired"]
    by_lane = defaultdict(list)
    for n in nodes:
        by_lane[n.get("lane") or "D12-civics"].append(n)
    batches = []
    for lane in sorted(by_lane):
        slug, title, prefix = TITLES[lane]
        rows = sorted(by_lane[lane], key=lambda n: (kr.AGES.index(n["age"]) if n["age"] in kr.AGES else 99, n["key"]))
        parts = [rows[i:i + size] for i in range(0, len(rows), size)]
        for j, part in enumerate(parts, 1):
            suffix = f"-{j}" if len(parts) > 1 else ""
            batches.append({
                "file": f"{slug}{suffix}.json", "title": title + (f" (part {j} of {len(parts)})" if len(parts) > 1 else ""),
                "lane": lane, "sourcePrefix": f"{prefix}{j if len(parts) > 1 else ''}",
                "sourcesFile": f"sources/{slug}{suffix}-sources.json",
                "ages": f"{part[0]['age']}–{part[-1]['age']}", "count": len(part), "ids": [n["id"] for n in part]})
    kr.dump_json({"_doc": "Corpus writing batches generated by tools/corpus_plan.py from the canonical proposal files.",
                  "nodeCount": len(nodes), "batches": batches}, kr.PKG / "corpus" / "plan.json")
    kr.dump_json({"_doc": "Corpus topic files (canonical educational texts). Generated by tools/corpus_plan.py.",
                  "files": [{"file": b["file"], "title": b["title"], "lane": b["lane"], "count": b["count"]}
                            for b in batches]}, kr.PKG / "corpus" / "index.json")
    print(f"{len(nodes)} nodes in {len(batches)} batches")
    for b in batches:
        print(f"  {b['file']:40s} {b['count']:3d}  {b['ages']}  prefix {b['sourcePrefix']}")


if __name__ == "__main__":
    main(sys.argv[1:])
