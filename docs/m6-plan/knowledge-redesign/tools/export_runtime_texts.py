#!/usr/bin/env python3
"""Export the educational texts the game shows to Sim.Data/content/knowledge-texts.json (display text only).

Director instruction, 2026-10-23 (M6 review item 4): the game UI shows each node's educational text naturally — no
citations, source badges, verification labels or bibliography — while provenance and evidence status stay in the
repository (corpus/*.json, sources/register.json, corpus/unresolved-claims.md) for internal quality control. Showing a
text in the game does NOT mark it fact-checked: its status in the corpus is unchanged.

The export holds, per runtime research node that has a corpus entry, its id and its description, sorted by id. Nothing
else crosses: no source ids, URLs, claims, statuses or notes. A runtime node without a corpus entry (the two merges
deferred by ADR-045) simply has no text.

Usage: python3 -I tools/export_runtime_texts.py          # write
       python3 -I tools/export_runtime_texts.py --check  # exit 1 if the tracked file differs from a fresh export
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kr_lib as kr  # noqa: E402

OUT = kr.CONTENT / "knowledge-texts.json"


def build():
    research = kr.load_json(kr.CONTENT / "research.json")
    runtime = {n["id"] for n in research["technologies"] + research["civics"]}
    texts = {}
    for f in sorted((kr.PKG / "corpus").glob("*.json")):
        if f.name in ("index.json", "plan.json"):
            continue
        for e in kr.load_json(f):
            if e["id"] in runtime:
                texts[e["id"]] = " ".join((e.get("description") or "").split())
    doc = {
        "_doc": ("Educational texts shown in the research views (generated by docs/m6-plan/knowledge-redesign/tools/"
                 "export_runtime_texts.py from the corpus; do not edit by hand). DISPLAY TEXT ONLY: provenance and the "
                 "evidence status of every text are kept in docs/m6-plan/knowledge-redesign/corpus and sources (internal "
                 "quality control; most texts are not yet source-checked). Not read by the simulation."),
        "texts": [{"id": i, "text": texts[i]} for i in sorted(texts)],
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main(argv):
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale: run tools/export_runtime_texts.py")
            return 1
        print("knowledge-texts.json is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {text.count('\"id\"')} texts")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
