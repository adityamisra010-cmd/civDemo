#!/usr/bin/env python3
"""Static gate model for a separate, population-led Civics Points (CP) economy.

DESIGN-PACKAGE TOOLING ONLY (no runtime coupling; reads production content and the
MEASURED baseline traces read-only). Every turn figure this tool writes is an
ESTIMATE from a static model, never a simulation result: no simulation of the
proposed graph or of any CP economy exists.

Question answered (cp-economy-proposal.md section 4): if Civics Points are generated by
their OWN equation (not a fraction of RP), how late can the civic atom
`legal_code_roman` (civics key 1002) make
  - the research stage (Option A keeps the atom; Option B removes it from the stage),
  - university eligibility (inst.university = library AND legal_code_roman, both options),
  - the A5 CORE facts (a5_systematic_law AND a5_coinage, both options),
  - the OR-route of Option C (legal_code_roman OR civil_service_examinations)?

Candidate CP equation (PROPOSED, placeholder coefficients, population term only —
institution/specialist terms do not exist in the running build and are zero here):

  reading Y (law 3, per sim-year):  CP_turn = c_y * P^beta * dtYears
  reading T (ADR-043 analogue):     CP_turn = c_t * P^beta
  anchor (PROPOSED placeholder):    CP_turn(P0 = 5,000, dt = 10) = 31 * s
                                    -> c_y = 3.1 s / P0^beta,  c_t = 31 s / P0^beta
  sensitivity: beta in BETAS, scale s in SCALES, detour E (CP spent on other civics
  after writing, before law_code) in DETOURS.

Model, per seed and driver (MEASURED inputs, ESTIMATE outputs):
  - population P(t) and dtYears(t): the measured traces (driver: population-trace;
    AI polity 2: ai-polity-population, opening population, dt from the global era
    table = the driver trace at the same turn);
  - technology timings: the MEASURED one-pool completion turns; the stage's technology
    part in a CP world is estimated with the RP the one-pool run spent on civics before
    the stage returned to technology ("freed RP"), and also reported without that
    acceleration (conservative);
  - a CP queue simulated turn by turn: taxation first once its prerequisites are known
    (the AI's tax goal; the driver's cheapest-first also takes it early), then a detour of
    E CP, then law_code and legal_code_roman (available only after the first writing
    node completes); CP that reaches no queued civic goes to other civics; one completion
    per turn; overflow is LOST (today's rule; D-R/KD-11 open).

Usage: python3 -I tools/cp_gate.py [--json data/balance-cp-gate.json]
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kr_lib as kr  # noqa: E402

SEEDS = (1, 2, 42, 7)
DRIVERS = ("ai", "driver")
BETAS = (0.5, 0.6, 0.7, 0.8)
SCALES = (0.1, 0.25, 0.5, 1.0, 2.0)
DETOURS = (0.0, 5000.0, 10000.0, 30000.0)
READINGS = ("Y", "T")
P0, DT0, ANCHOR_CP_TURN = 5000.0, 10.0, 31.0
WRITING = ("cuneiform", "hieroglyphic", "chinese_script")
P2_TURNS = 10
MEAS = kr.PKG / "measurements"


def read_csv(path):
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def driver_trace(seed):
    rows = read_csv(MEAS / "raw" / f"population-trace-seed{seed}.csv")
    return {int(r["turn"]): (float(r["population"]), float(r["dtYears"]), float(r["researchPointsThisTurn"]),
                             float(r["simYear"])) for r in rows}


def ai_trace(seed, dt_of):
    out = {}
    for r in read_csv(MEAS / "raw" / "ai" / f"ai-polity-population-seed{seed}.csv"):
        if int(r["controller"]) != 2:
            continue
        t = int(r["turn"])
        pop = float(r["population_opening"])
        rp = 0.08 * pop ** 0.699 if pop > 0 else 0.0
        out[t] = (pop, dt_of[t][1], rp, dt_of[t][3])
    return out


def completions(driver):
    name = "baseline-ai-node-completions.csv" if driver == "ai" else "baseline-node-completions.csv"
    out = {}
    for r in read_csv(MEAS / name):
        out.setdefault(int(r["seed"]), {})[r["node_id"]] = int(r["completion_turn"])
    return out


def content():
    research = kr.load_json(kr.CONTENT / "research.json")
    cost = {n["id"]: float(n["cost"]) for n in research["technologies"] + research["civics"]}
    tree = {n["id"]: "technology" for n in research["technologies"]}
    tree.update({n["id"]: "civics" for n in research["civics"]})
    ent = {e["id"].split(".", 1)[1]: e.get("requires") for e in research["entities"]
           if e["id"].startswith("inst.")}
    return research, cost, tree, ent


def turn_of(ast, done, ent, override=None):
    """Earliest turn at which an expression holds over MEASURED completion turns (OR = min,
    AND = max; entity short ids resolve through their own requirement). None = never."""
    override = override or {}
    if ast is None:
        return 0
    kind = ast[0]
    if kind == "atom":
        a = ast[1]
        if a in override:
            return override[a]
        if a in done:
            return done[a]
        if a in ent and ent[a]:
            return turn_of(kr.parse(ent[a]), done, ent, override)
        return None
    vals = [turn_of(x, done, ent, override) for x in ast[1]]
    if kind == "and":
        return None if any(v is None for v in vals) else max(vals)
    if kind == "or":
        vals = [v for v in vals if v is not None]
        return min(vals) if vals else None
    return None


def cp_turn(reading, beta, scale, pop, dt):
    if pop <= 0:
        return 0.0
    if reading == "Y":
        return (ANCHOR_CP_TURN / DT0) * scale / P0 ** beta * pop ** beta * dt
    return ANCHOR_CP_TURN * scale / P0 ** beta * pop ** beta


def queue_sim(trace, cpf, items):
    """items: list of (label, cost, available_turn or None, needs_previous). Returns completion
    turn per label (None = not within the horizon). CP flows into the first available
    unfinished item in list order; an item that needs its predecessor waits for it; one
    completion per turn; overflow lost."""
    done = {}
    progress = {lab: 0.0 for lab, *_ in items}
    for t in sorted(trace):
        pop, dt, _rp, _y = trace[t]
        cp = cpf(pop, dt)
        for i, (lab, cost, avail, needs_prev) in enumerate(items):
            if lab in done:
                continue
            if avail is None or t < avail:
                continue
            if needs_prev and i > 0 and items[i - 1][0] not in done:
                continue
            progress[lab] += cp
            if progress[lab] >= cost:
                done[lab] = t
            break
    return {lab: done.get(lab) for lab, *_ in items}


def cum_turn(trace, amount, key=2):
    acc = 0.0
    for t in sorted(trace):
        acc += trace[t][key]
        if acc >= amount:
            return t
    return None


def cum_at(trace, turn, key=2):
    return sum(v[key] for t, v in trace.items() if t <= turn)


def analyse():
    research, cost, tree, ent = content()
    stage_ast = kr.parse(research["researchStage"]["requires"])
    stage_tech_ast = kr.parse("medicine_hippocratic AND (geometry_axiomatic OR algebra) AND stamp_seal")
    univ_ast = kr.parse(ent["university"])
    tax_ast = kr.parse(next(n["prereq"] for n in research["civics"] if n["id"] == "taxation"))
    appointed = "taxation AND (cuneiform OR hieroglyphic OR chinese_script)"  # PROPOSED civic, civics-tree-proposal.json
    cse_cost = 2090.0 + 5910.0  # appointed_officials + civil_service_examinations (PROPOSED costs)
    comp = {d: completions(d) for d in DRIVERS}
    base = {}
    for seed in SEEDS:
        dtr = driver_trace(seed)
        traces = {"driver": dtr, "ai": ai_trace(seed, dtr)}
        for d in DRIVERS:
            done = comp[d][seed]
            tr = traces[d]
            t_write = min(done[w] for w in WRITING if w in done)
            t_stage = turn_of(stage_ast, done, ent)
            t_stage_tech_onepool = turn_of(stage_tech_ast, done, ent)
            civic_rp_before = sum(cost[n] for n, t in done.items() if tree.get(n) == "civics" and t <= t_stage)
            t_stage_tech_fast = cum_turn(tr, cum_at(tr, t_stage) - civic_rp_before)
            base[(seed, d)] = {
                "seed": seed, "driver": d, "trace": tr, "done": done,
                "T_writing": t_write, "T_tax_prereq": turn_of(tax_ast, done, ent),
                "T_paper": done.get("paper"), "T_coinage": done.get("coinage_electrum"),
                "T_library": turn_of(kr.parse("library"), done, ent),
                "onePool": {"T_lcr": done.get("legal_code_roman"), "T_stage": t_stage,
                            "T_univ": turn_of(univ_ast, done, ent),
                            "T_A5core": max(done.get("legal_code_roman"), done.get("coinage_electrum"))},
                "T_stageTech": {"conservative": t_stage_tech_onepool, "freedRP": min(t_stage_tech_onepool, t_stage_tech_fast)},
                "civicRPBeforeStage": civic_rp_before,
            }
    cases = []
    for (seed, d), b in sorted(base.items()):
        for reading in READINGS:
            for beta in BETAS:
                for s in SCALES:
                    cpf = (lambda pop, dt, r=reading, be=beta, sc=s: cp_turn(r, be, sc, pop, dt))
                    window = sum(cpf(v[0], v[1]) for t, v in b["trace"].items()
                                 if b["T_writing"] < t <= b["onePool"]["T_stage"])
                    for E in DETOURS:
                        items = [("taxation", cost["taxation"], b["T_tax_prereq"], False),
                                 ("detour", E, b["T_writing"], False) if E > 0 else ("detour", 0.0, None, False),
                                 ("law_code", cost["law_code"], b["T_writing"], False),
                                 ("legal_code_roman", cost["legal_code_roman"], b["T_writing"], True)]
                        q = queue_sim(b["trace"], cpf, items)
                        t_lcr = q["legal_code_roman"]
                        # Option C: the examination route (needs paper; PROPOSED civics)
                        t_appointed_avail = turn_of(kr.parse(appointed), b["done"], ent, {"taxation": q["taxation"]}) \
                            if q["taxation"] is not None else None
                        qc = queue_sim(b["trace"], cpf, [
                            ("taxation", cost["taxation"], b["T_tax_prereq"], False),
                            ("detour", E, b["T_writing"], False) if E > 0 else ("detour", 0.0, None, False),
                            ("exam_route", cse_cost, t_appointed_avail, False)])
                        t_exam = None if qc["exam_route"] is None or b["T_paper"] is None else max(qc["exam_route"], b["T_paper"])
                        row = {"seed": seed, "driver": d, "reading": reading, "beta": beta, "scale": s, "detourCP": E,
                               "cpPerTurnAtAnchor": round(cp_turn(reading, beta, s, P0, DT0), 3),
                               "cpWindowWritingToOnePoolStage": round(window, 1),
                               "T_taxation": q["taxation"], "T_lcr": t_lcr}
                        for variant, t_tech in b["T_stageTech"].items():
                            a = None if t_lcr is None else max(t_tech, t_lcr)
                            row[f"A_stage_{variant}"] = a
                            row[f"A_delay_{variant}"] = None if a is None else a - b["onePool"]["T_stage"]
                            row[f"A_civicLag_{variant}"] = None if a is None else a - t_tech
                            row[f"B_stage_{variant}"] = t_tech
                            row[f"B_delay_{variant}"] = t_tech - b["onePool"]["T_stage"]
                        univ = None if t_lcr is None or b["T_library"] is None else max(b["T_library"], t_lcr)
                        row["univ"] = univ
                        row["univ_delay"] = None if univ is None else univ - b["onePool"]["T_univ"]
                        a5 = None if t_lcr is None else max(b["T_coinage"], t_lcr)
                        row["A5core"] = a5
                        row["A5core_delay"] = None if a5 is None else a5 - b["onePool"]["T_A5core"]
                        t_c = min([x for x in (t_lcr, t_exam) if x is not None], default=None)
                        row["C_civicTurn"] = t_c
                        row["C_examRouteTurn"] = t_exam
                        row["C_gain"] = None if t_c is None or t_lcr is None else t_lcr - t_c
                        cases.append(row)
    return base, cases


def summarise(base, cases):
    def worst(rows, key):
        vals = [r[key] for r in rows]
        return None if any(v is None for v in vals) else max(vals)

    grid = []
    for reading in READINGS:
        for beta in BETAS:
            for s in SCALES:
                for E in DETOURS:
                    rows = [r for r in cases if r["reading"] == reading and r["beta"] == beta and r["scale"] == s
                            and r["detourCP"] == E]
                    grid.append({
                        "reading": reading, "beta": beta, "scale": s, "detourCP": E,
                        "cpPerTurnAtAnchor": rows[0]["cpPerTurnAtAnchor"],
                        "A_maxStageDelay_freedRP": worst(rows, "A_delay_freedRP"),
                        "A_maxStageDelay_conservative": worst(rows, "A_delay_conservative"),
                        "A_maxCivicLag_freedRP": worst(rows, "A_civicLag_freedRP"),
                        "A_P2pass": all(r["A_delay_conservative"] is not None and r["A_delay_conservative"] <= P2_TURNS
                                        for r in rows),
                        "B_stageDelayRange_freedRP": [min(r["B_delay_freedRP"] for r in rows),
                                                      max(r["B_delay_freedRP"] for r in rows)],
                        "maxUniversityDelay": worst(rows, "univ_delay"),
                        "maxA5coreDelay": worst(rows, "A5core_delay"),
                        "C_maxGainTurns": max((r["C_gain"] or 0) for r in rows),
                        "anyNever": any(r["T_lcr"] is None for r in rows),
                        "bindingCase": (lambda m: None if m is None else f"seed {m['seed']} / {m['driver']}")(
                            max((r for r in rows if r["A_delay_conservative"] is not None),
                                key=lambda r: (r["A_delay_conservative"], -r["seed"]), default=None)),
                    })
    thresholds = []
    for reading in READINGS:
        for beta in BETAS:
            for E in DETOURS:
                ok = [g["scale"] for g in grid if g["reading"] == reading and g["beta"] == beta and g["detourCP"] == E
                      and g["A_P2pass"]]
                thresholds.append({"reading": reading, "beta": beta, "detourCP": E,
                                   "smallestScalePassingP2": min(ok) if ok else None})
    late = []
    for (seed, d), b in sorted(base.items()):
        for reading in READINGS:
            for beta in (0.6, 0.7):
                pts = []
                for t in (300, 700, 1000, 1300, 1600):
                    pop, dt, rp, year = b["trace"][t]
                    cpt = cp_turn(reading, beta, 1.0, pop, dt)
                    pts.append({"turn": t, "simYear": year, "dtYears": dt, "population": pop,
                                "cpPerTurn": round(cpt, 2),
                                "turnsFor10kCP": None if cpt <= 0 else round(10000.0 / cpt, 1)})
                late.append({"seed": seed, "driver": d, "reading": reading, "beta": beta, "scale": 1.0, "points": pts})
    baseline = []
    for (seed, d), b in sorted(base.items()):
        baseline.append({"seed": seed, "driver": d, "T_writing": b["T_writing"], "T_tax_prereq": b["T_tax_prereq"],
                         "T_library": b["T_library"], "T_coinage": b["T_coinage"], "T_paper": b["T_paper"],
                         "onePool": b["onePool"], "T_stageTech": b["T_stageTech"],
                         "civicRPBeforeStage": b["civicRPBeforeStage"]})
    return grid, thresholds, baseline, late


def main(argv):
    base, cases = analyse()
    grid, thresholds, baseline, late = summarise(base, cases)
    doc = {
        "_label": "ESTIMATE (static model, tools/cp_gate.py) - NOT a simulation result; no simulation of the proposed graph "
                  "or of any Civics Points economy exists. Inputs labelled MEASURED are read from measurements/.",
        "status": "PROPOSED analysis for Director review; every coefficient is a PROPOSED placeholder",
        "equation": {
            "readingY": "CP_turn = c_y * P^beta * dtYears (per sim-year rate, law 3)",
            "readingT": "CP_turn = c_t * P^beta (per strategic turn; needs its own ADR, D-061.2)",
            "anchor": f"CP_turn(P={P0:.0f}, dt={DT0:.0f}) = {ANCHOR_CP_TURN} * scale (PROPOSED placeholder)",
            "notModelled": "institution/specialist terms (none exist in the running build: zero here, so CP is a lower "
                           "bound with respect to them); Eurekas; foreign exposure; CP lost before the first civic is "
                           "available (the A1-A2 civics of the proposal absorb it)",
            "notRP": "CP is never computed from RP here; RP appears only in the MEASURED technology timings",
        },
        "grids": {"readings": list(READINGS), "betas": list(BETAS), "scales": list(SCALES), "detoursCP": list(DETOURS),
                  "seeds": list(SEEDS), "drivers": list(DRIVERS), "P2turns": P2_TURNS},
        "baselineMeasured": baseline,
        "thresholds": thresholds,
        "lateGamePerTurn": late,
        "summary": grid,
        "cases": cases,
    }
    out = argv[argv.index("--json") + 1] if "--json" in argv else str(kr.DATA / "balance-cp-gate.json")
    kr.dump_json(doc, out)
    print("ESTIMATE (static model) - written", out)
    for th in thresholds:
        if th["detourCP"] in (0.0, 10000.0):
            print(f"  reading {th['reading']} beta {th['beta']} detour {th['detourCP']:>7.0f}: smallest scale passing P2 = "
                  f"{th['smallestScalePassingP2']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
