#!/usr/bin/env python3
"""Record evidence progress per corpus batch and write the remaining sourcing queue.

DESIGN-PACKAGE TOOLING ONLY. Reads corpus/*.json (canonical texts) and corpus/plan.json (the batches written by
tools/corpus_plan.py); adds an `evidence` block to every batch in plan.json (counts by fact-check status and the ids
still blocked) and writes corpus/sourcing-queue.md. Re-running it after a sourcing pass is idempotent.

The queue order inside a batch is the priority the Director set (2026-10-22): new nodes, then civic/regime
claims, then entries whose notes record a disputed or conflicting date, then the rest. Nothing here promotes a
status: it only reports what the entries say.

Usage: python3 -I tools/sourcing_queue.py
"""
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kr_lib as kr  # noqa: E402

ORDER = ("unverified", "partially-checked", "search-corroborated", "source-checked")
DISPUTE_WORDS = ("conflict", "contradict", "disput", "contested", "emerged date", "proposal's")


def priority(e, new_ids):
    fc = e.get("factCheck") or {}
    text = ((e.get("uncertainty") or "") + " " + (fc.get("notes") or "")).lower()
    return (0 if e["id"] in new_ids else 1, 0 if e.get("tree") == "civics" else 1,
            0 if any(w in text for w in DISPUTE_WORDS) else 1, ORDER.index(fc.get("status", "unverified")), e["id"])


def main():
    tech = kr.load_json(kr.PKG / "technology-tree-proposal.json")
    civ = kr.load_json(kr.PKG / "civics-tree-proposal.json")
    new_ids = {n["id"] for n in tech["nodes"] + civ["nodes"] if n["status"] == "new"}
    plan_path = kr.PKG / "corpus" / "plan.json"
    plan = kr.load_json(plan_path)
    total = Counter()
    lines = ["# Corpus sourcing queue (generated)", "",
             "Generated by `tools/sourcing_queue.py` from `corpus/*.json`. **Every entry below is BLOCKED from shipping "
             "as educational fact** until its status is `source-checked` (source page or document opened and each claim "
             "confirmed). `search-corroborated` means the claims matched search-result text only; it is not a page check. "
             "Order within a batch: new nodes, civics, dated/disputed claims, then the rest.", ""]
    rows = []
    for b in plan["batches"]:
        entries = kr.load_json(kr.PKG / "corpus" / b["file"])
        st = Counter((e.get("factCheck") or {}).get("status", "unverified") for e in entries)
        total.update(st)
        blocked = sorted((e for e in entries if (e.get("factCheck") or {}).get("status") != "source-checked"),
                         key=lambda e: priority(e, new_ids))
        b["evidence"] = {"byStatus": {k: st.get(k, 0) for k in ORDER},
                         "blocked": [e["id"] for e in blocked]}
        rows.append((b, st, blocked))
    plan["evidenceDoc"] = ("evidence: counts by fact-check status and the ids still blocked from shipping, in queue "
                           "order; refreshed by tools/sourcing_queue.py")
    kr.dump_json(plan, plan_path)
    lines += ["| Status | Entries |", "|---|---|"] + [f"| {k} | {total.get(k, 0)} |" for k in ORDER]
    lines += ["", f"Blocked from shipping: **{sum(total.values()) - total.get('source-checked', 0)}** of "
                  f"{sum(total.values())}.", ""]
    for b, st, blocked in rows:
        lines += [f"## {b['title']} — `corpus/{b['file']}` (sources `{b['sourcesFile']}`)", "",
                  " · ".join(f"{k} {st.get(k, 0)}" for k in ORDER), ""]
        for e in blocked:
            s = (e.get("factCheck") or {}).get("status", "unverified")
            tag = " (new)" if e["id"] in new_ids else ""
            lines.append(f"- `{e['id']}`{tag} — {s}")
        lines.append("")
    (kr.PKG / "corpus" / "sourcing-queue.md").write_text("\n".join(lines), encoding="utf-8")
    print("by status:", {k: total.get(k, 0) for k in ORDER})


if __name__ == "__main__":
    main()
