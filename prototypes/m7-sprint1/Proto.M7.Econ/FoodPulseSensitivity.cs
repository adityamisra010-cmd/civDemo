using System.Globalization;
using System.Text;

namespace Proto.M7.Econ;

/// <summary>
/// Verification round 2 (F2-1, F2-2): how the war-window outcomes depend on the length of the settlement period and on the
/// length of the march leg, varied APART. Before round 2 the two were the same number (one move of the pulse's length per
/// pulse), so every march figure moved with the unratified pulse length (D-079 Q1). Reporting code only: loops, no LINQ,
/// culture-invariant formatting. T0 = 25, horizon 20 turns, CapBeforeMilitary, FULL haul, growth as headroom, 6 seeds.
/// </summary>
public static class FoodPulseSensitivity
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>The lengths swept (days). 21 is T2's proposed Neolithic pulse, the battery's value at T0 = 25.</summary>
    public static readonly long[] Lengths = [7, 14, 21, 42];

    public const long ProposedPulseAtT0 = 21;

    public static FoodScenario ScenarioOf(BaselineSeries s, FoodModelParams p, string army, string regime, AllocationOrder order,
        UnfedConsequence consequence, long periodDays, long legDays)
    {
        RegimeSpec? spec = null;
        foreach (RegimeSpec r in FoodComparison.DefaultPlan().Regimes) if (r.Name == regime) spec = r;
        return FoodComparison.Scenario(s, p, new EpochPlan(25, 20), army, spec ?? throw new ArgumentException(regime), order,
            OverflowRule.CapBeforeMilitary, consequence, HaulBasis.FullLoad) with { PulseDays = periodDays, MarchLegDays = legDays };
    }

    public static FoodRunResult RunOne(BaselineSeries s, FoodModelParams p, string army, string regime, AllocationOrder order,
        UnfedConsequence consequence, long periodDays, long legDays) =>
        FoodPulseModel.Run(s, ScenarioOf(s, p, army, regime, order, consequence, periodDays, legDays), p);

    public static string Report(BaselineSeries[] series, FoodModelParams p)
    {
        var sb = new StringBuilder();
        sb.Append("# Lane F verification round 2: settlement period and march leg (generated by `food-pulse`)\n\n");
        sb.Append("T0 = 25, horizon 20 turns, CapBeforeMilitary, FULL haul, growth as headroom, consequence None unless stated; ")
          .Append("means over ").Append(series.Length.ToString(Inv)).Append(" seeds of per-seed window ratios. ")
          .Append("Haul per march day = window haul requested ÷ window march days requested.\n\n");

        string[] armies = ["WAR-1000", "WAR-500"];
        sb.Append("## A. Settlement period varied, march leg fixed at 21 d (dt-correctness of the haul bill)\n\n");
        MarchTable(sb, series, p, armies, fixedLeg: true);
        sb.Append("## B. March leg varied, settlement period fixed at 21 d (the physical resupply interval)\n\n");
        MarchTable(sb, series, p, armies, fixedLeg: false);
        sb.Append("## C. Leg = period (the march definition before round 2: one move of the period's length per period; growth claim as in round 2)\n\n");
        MarchTableTied(sb, series, p, armies);

        sb.Append("## D. Desert: soldiers at the window's end, WAR-1000, BAD-1s (CGM / CMG per seed)\n\n");
        sb.Append("| period (d) | leg (d) |");
        for (int i = 0; i < series.Length; i++) sb.Append(" seed ").Append(series[i].Seed.ToString(Inv)).Append(" |");
        sb.Append(" mean CGM / CMG |\n|---|---|");
        for (int i = 0; i < series.Length; i++) sb.Append("---|");
        sb.Append("---|\n");
        for (int k = 0; k < Lengths.Length; k++) DesertRow(sb, series, p, "WAR-1000", "BAD-1s", Lengths[k], ProposedPulseAtT0, UnfedConsequence.Desert);
        for (int k = 0; k < Lengths.Length; k++)
            if (Lengths[k] != ProposedPulseAtT0) DesertRow(sb, series, p, "WAR-1000", "BAD-1s", ProposedPulseAtT0, Lengths[k], UnfedConsequence.Desert);
        for (int k = 0; k < Lengths.Length; k++)
            if (Lengths[k] != ProposedPulseAtT0) DesertRow(sb, series, p, "WAR-1000", "BAD-1s", Lengths[k], Lengths[k], UnfedConsequence.Desert);
        sb.Append('\n');

        sb.Append("## E. Desert without a march: soldiers at the window's end, GARRISON-1000, SEVERE-2s (CGM / CMG per seed)\n\n");
        sb.Append("| period (d) | leg (d) |");
        for (int i = 0; i < series.Length; i++) sb.Append(" seed ").Append(series[i].Seed.ToString(Inv)).Append(" |");
        sb.Append(" mean CGM / CMG |\n|---|---|");
        for (int i = 0; i < series.Length; i++) sb.Append("---|");
        sb.Append("---|\n");
        for (int k = 0; k < Lengths.Length; k++) DesertRow(sb, series, p, "GARRISON-1000", "SEVERE-2s", Lengths[k], ProposedPulseAtT0, UnfedConsequence.Desert);
        sb.Append('\n');

        sb.Append("## F. Starve (a per-year law) for comparison: soldiers at the window's end, WAR-1000, BAD-1s (CGM / CMG per seed)\n\n");
        sb.Append("| period (d) | leg (d) |");
        for (int i = 0; i < series.Length; i++) sb.Append(" seed ").Append(series[i].Seed.ToString(Inv)).Append(" |");
        sb.Append(" mean CGM / CMG |\n|---|---|");
        for (int i = 0; i < series.Length; i++) sb.Append("---|");
        sb.Append("---|\n");
        for (int k = 0; k < Lengths.Length; k++) DesertRow(sb, series, p, "WAR-1000", "BAD-1s", Lengths[k], ProposedPulseAtT0, UnfedConsequence.Starve);
        sb.Append('\n');
        return sb.ToString();
    }

    private static void MarchTable(StringBuilder sb, BaselineSeries[] series, FoodModelParams p, string[] armies, bool fixedLeg)
    {
        sb.Append("| army | period (d) | leg (d) | window march days | haul requested | haul per march day | march granted % CGM / CMG | growth served % CGM / CMG |\n");
        sb.Append("|---|---|---|---|---|---|---|---|\n");
        for (int a = 0; a < armies.Length; a++)
            for (int k = 0; k < Lengths.Length; k++)
            {
                long period = fixedLeg ? Lengths[k] : ProposedPulseAtT0, leg = fixedLeg ? ProposedPulseAtT0 : Lengths[k];
                MarchRow(sb, series, p, armies[a], period, leg);
            }
        sb.Append('\n');
    }

    private static void MarchTableTied(StringBuilder sb, BaselineSeries[] series, FoodModelParams p, string[] armies)
    {
        sb.Append("| army | period (d) | leg (d) | window march days | haul requested | haul per march day | march granted % CGM / CMG | growth served % CGM / CMG |\n");
        sb.Append("|---|---|---|---|---|---|---|---|\n");
        for (int a = 0; a < armies.Length; a++)
            for (int k = 0; k < Lengths.Length; k++) MarchRow(sb, series, p, armies[a], Lengths[k], Lengths[k]);
        sb.Append('\n');
    }

    private static void MarchRow(StringBuilder sb, BaselineSeries[] series, FoodModelParams p, string army, long period, long leg)
    {
        double marchCgm = 0, marchCmg = 0, growthCgm = 0, growthCmg = 0, haul = 0, days = 0;
        for (int i = 0; i < series.Length; i++)
        {
            FoodRunResult g = RunOne(series[i], p, army, "NORMAL", AllocationOrder.CivilianGrowthMilitary, UnfedConsequence.None, period, leg);
            FoodRunResult m = RunOne(series[i], p, army, "NORMAL", AllocationOrder.CivilianMilitaryGrowth, UnfedConsequence.None, period, leg);
            marchCgm += Ratio(g.War.MarchDaysGranted, g.War.MarchDaysRequested);
            marchCmg += Ratio(m.War.MarchDaysGranted, m.War.MarchDaysRequested);
            growthCgm += Ratio(g.War.GrowthGranted, g.War.GrowthDemand);
            growthCmg += Ratio(m.War.GrowthGranted, m.War.GrowthDemand);
            haul += g.War.HaulRequested;
            days += g.War.MarchDaysRequested;
        }
        double n = series.Length;
        sb.Append("| ").Append(army).Append(" | ").Append(L(period)).Append(" | ").Append(L(leg)).Append(" | ").Append((days / n).ToString("F0", Inv))
          .Append(" | ").Append((haul / n).ToString("F0", Inv)).Append(" | ").Append((haul / days).ToString("F2", Inv))
          .Append(" | ").Append(Pct(marchCgm / n)).Append(" / ").Append(Pct(marchCmg / n))
          .Append(" | ").Append(Pct(growthCgm / n)).Append(" / ").Append(Pct(growthCmg / n)).Append(" |\n");
    }

    private static void DesertRow(StringBuilder sb, BaselineSeries[] series, FoodModelParams p, string army, string regime, long period, long leg,
        UnfedConsequence consequence)
    {
        sb.Append("| ").Append(L(period)).Append(" | ").Append(L(leg)).Append(" |");
        long sumG = 0, sumM = 0;
        for (int i = 0; i < series.Length; i++)
        {
            long g = RunOne(series[i], p, army, regime, AllocationOrder.CivilianGrowthMilitary, consequence, period, leg).WarSoldiersAtEnd;
            long m = RunOne(series[i], p, army, regime, AllocationOrder.CivilianMilitaryGrowth, consequence, period, leg).WarSoldiersAtEnd;
            sumG += g;
            sumM += m;
            sb.Append(' ').Append(L(g)).Append(" / ").Append(L(m)).Append(" |");
        }
        double n = series.Length;
        sb.Append(' ').Append((sumG / n).ToString("F0", Inv)).Append(" / ").Append((sumM / n).ToString("F0", Inv)).Append(" |\n");
    }

    private static double Ratio(long num, long den) => den > 0 ? num / (double)den : 1.0;
    private static string Pct(double r) => (100.0 * r).ToString("F1", Inv);
    private static string L(long v) => v.ToString(Inv);
}
